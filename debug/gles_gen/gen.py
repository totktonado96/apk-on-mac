#!/usr/bin/env python3
# debug/gles_gen/gen.py
#
# WHAT: Generator for the android.opengl.GLES30/31/31Ext/32 Java binding
# surface and its JNI bridges. Parses `javap -p -constants` output for each
# class (captured in /tmp/glsig or alongside this script) and emits, IN
# LOCKSTEP, three artifacts per method so a Java `native` decl can NEVER be
# left unregistered:
#   (a) the Java `public static native` decl (exact AOSP signature),
#   (b) a C++ JNI bridge that lazily resolves the underlying GL entry point
#       via eglGetProcAddress/dlsym (no-op / GL_INVALID_OPERATION fallback so
#       a missing ANGLE symbol can never hard-fail RegisterNatives), and
#   (c) the JNINativeMethod table entry binding (a)->(b).
#
# WHY a generator: the surface is ~412 methods. Hand-writing the Java decl,
# the C++ fn, and the registration entry separately is exactly how the prior
# attempt shipped 141 unregistered `native` decls. Deriving all three from one
# parsed signature makes lockstep structural, not a discipline problem.
#
# This script is a build-time author tool, not shipped runtime code. Re-run it
# only to regenerate from a newer android.jar. Output is committed.
import re, sys, os

SRC = os.path.dirname(os.path.abspath(__file__))
SIG_DIR = "/tmp/glsig"

CLASSES = ["GLES30", "GLES31", "GLES31Ext", "GLES32"]
EXTENDS = {"GLES30": "GLES20", "GLES31": "GLES30", "GLES32": "GLES31",
           "GLES31Ext": None}

# Map a javap Java type to (jni_jtype, descriptor_char_or_str).
JNI = {
    "void":    ("void",      "V"),
    "int":     ("jint",      "I"),
    "boolean": ("jboolean",  "Z"),
    "float":   ("jfloat",    "F"),
    "long":    ("jlong",     "J"),
    "byte":    ("jbyte",     "B"),
    "int[]":     ("jintArray",    "[I"),
    "float[]":   ("jfloatArray",  "[F"),
    "long[]":    ("jlongArray",   "[J"),
    "byte[]":    ("jbyteArray",   "[B"),
    "boolean[]": ("jbooleanArray","[Z"),
    "java.lang.String":   ("jstring",      "Ljava/lang/String;"),
    "java.lang.String[]": ("jobjectArray", "[Ljava/lang/String;"),
    "java.nio.Buffer":      ("jobject", "Ljava/nio/Buffer;"),
    "java.nio.IntBuffer":   ("jobject", "Ljava/nio/IntBuffer;"),
    "java.nio.FloatBuffer": ("jobject", "Ljava/nio/FloatBuffer;"),
    "java.nio.LongBuffer":  ("jobject", "Ljava/nio/LongBuffer;"),
    "java.nio.ByteBuffer":  ("jobject", "Ljava/nio/ByteBuffer;"),
}
# Callback interface params: bind as descriptor, ignore the value in the bridge.
CB = {
    "android.opengl.GLES32$DebugProc":        "Landroid/opengl/GLES32$DebugProc;",
    "android.opengl.GLES31Ext$DebugProcKHR":  "Landroid/opengl/GLES31Ext$DebugProcKHR;",
}

NATIVE_RE = re.compile(
    r"public static native\s+([\w.$\[\]]+)\s+(\w+)\s*\(([^)]*)\)")
CONST_RE = re.compile(
    r"public static final (int|long)\s+(\w+)\s*=\s*(-?\d+)l?;")

def parse(cls):
    consts, methods = [], []
    with open(os.path.join(SIG_DIR, cls + ".txt")) as f:
        for line in f:
            m = CONST_RE.search(line)
            if m:
                consts.append((m.group(1), m.group(2), m.group(3)))
                continue
            m = NATIVE_RE.search(line)
            if m:
                ret, name, args = m.group(1), m.group(2), m.group(3).strip()
                params = [a.strip() for a in args.split(",")] if args else []
                methods.append((ret, name, params))
    return consts, methods

def descriptor(ret, params):
    def d(t):
        if t in JNI: return JNI[t][1]
        if t in CB:  return CB[t]
        raise SystemExit("unknown type " + t)
    return "(" + "".join(d(p) for p in params) + ")" + d(ret)

# ----- group overloads so we can name unique C++ bridges -----
def cpp_name(cls, name, idx, total):
    base = "GL3_%s_%s" % (cls, name)
    return base if total == 1 else "%s_%d" % (base, idx)

# A param classification for marshaling.
def pclass(t):
    if t in ("int","float","long","byte"): return "scalar"
    if t == "boolean": return "bool"
    if t.endswith("[]") and t != "java.lang.String[]": return "primarray"
    if t == "java.lang.String": return "string"
    if t == "java.lang.String[]": return "strarray"
    if t.startswith("java.nio."): return "buffer"
    if t in CB: return "callback"
    raise SystemExit("pclass? " + t)

JAVA_DIR = os.path.join(SRC, "..", "..", "runtime", "java", "android", "opengl")

JAVA_HEADER = """// android.opengl.%(cls)s -- GLES %(ver)s Java binding.
//
// GENERATED by debug/gles_gen/gen.py from the android-34 android.jar
// signatures (javap). Do NOT hand-edit: every `public static native` decl
// here is registered IN LOCKSTEP by the matching block in
// runtime/src/native_methods.cpp (table kGl3%(cls)sMethods). The C++ bridge
// lazily resolves the ANGLE GLES3 entry point (eglGetProcAddress/dlsym) with
// a safe fallback, so a missing symbol never breaks RegisterNatives. See
// docs/aosp-coverage-audit_2026-06-20/10-opengl-egl.md. Constants + signatures
// mirror AOSP android.opengl.%(cls)s exactly. (Project convention: no em dashes.)
package android.opengl;

import java.nio.Buffer;
import java.nio.ByteBuffer;
import java.nio.IntBuffer;
import java.nio.FloatBuffer;
import java.nio.LongBuffer;

public class %(cls)s%(extends)s {
    public %(cls)s() {}

"""

def java_type(t):
    # Render a javap type back to its Java source spelling.
    repl = {
        "java.lang.String": "String",
        "java.lang.String[]": "String[]",
        "java.nio.Buffer": "Buffer",
        "java.nio.IntBuffer": "IntBuffer",
        "java.nio.FloatBuffer": "FloatBuffer",
        "java.nio.LongBuffer": "LongBuffer",
        "java.nio.ByteBuffer": "ByteBuffer",
        "android.opengl.GLES32$DebugProc": "GLES32.DebugProc",
        "android.opengl.GLES31Ext$DebugProcKHR": "GLES31Ext.DebugProcKHR",
    }
    return repl.get(t, t)

def emit_java(cls):
    consts, methods = parse(cls)
    ext = EXTENDS[cls]
    out = [JAVA_HEADER % {
        "cls": cls, "ver": {"GLES30":"3.0","GLES31":"3.1",
                            "GLES31Ext":"3.1 ext","GLES32":"3.2"}[cls],
        "extends": (" extends " + ext) if ext else ""}]
    # Constants.
    for kind, name, val in consts:
        if kind == "long":
            out.append("    public static final long %s = %sL;\n" % (name, val))
        else:
            out.append("    public static final int %s = %s;\n" % (name, val))
    out.append("\n")
    # Nested callback interfaces (AOSP nests these as member interfaces).
    if cls == "GLES32":
        out.append("    public interface DebugProc {\n"
                   "        void onMessage(int source, int type, int id,"
                   " int severity, String message);\n    }\n\n")
    if cls == "GLES31Ext":
        out.append("    public interface DebugProcKHR {\n"
                   "        void onMessage(int source, int type, int id,"
                   " int severity, String message);\n    }\n\n")
    # Native method decls. Per-name argument naming a0,a1,...
    for ret, name, params in methods:
        decl_params = ", ".join("%s a%d" % (java_type(p), i)
                                for i, p in enumerate(params))
        out.append("    public static native %s %s(%s);\n"
                   % (java_type(ret), name, decl_params))
    out.append("}\n")
    path = os.path.join(JAVA_DIR, cls + ".java")
    with open(path, "w") as f:
        f.write("".join(out))
    return len(methods)

# ---------------- C++ bridge generation ----------------
#
# Strategy: every GL Java method name maps 1:1 to the GLES C entry point of the
# same name (the AOSP binding is a thin wrapper). We resolve the C symbol once
# via gl3_resolve("<name>") and call through a typed function pointer built from
# the param/return classification. Array/Buffer params marshal to a raw pointer;
# a trailing `int <x>Offset` paired with the preceding array advances it.
#
# We do NOT attempt to be a perfect re-impl of AOSP's hand-written JNI for the
# ~exotic out-param getters; the goal is: (1) never UnsatisfiedLinkError, (2)
# forward the common draw/state/uniform/VAO/instancing/compute calls correctly.

CPP_TYPEDEF = {
    "void":"void","int":"GLint","boolean":"GLboolean","float":"GLfloat",
    "long":"GLint64","byte":"GLbyte",
}

def is_offset_param(params, i):
    # True if params[i] is an `int` offset following an array param at i-1.
    return (i > 0 and params[i] == "int"
            and params[i-1].endswith("[]"))

def cpp_param_decl(p, i):
    jt = JNI.get(p, ("jobject",""))[0] if p not in CB else "jobject"
    return "%s a%d" % (jt, i)

def gl_ctype(t):
    # C type the GL entry point expects for a pointer-ish or scalar arg.
    if t in CPP_TYPEDEF: return CPP_TYPEDEF[t]
    if t == "int[]" or t.startswith("java.nio.IntBuffer"): return "GLint"
    if t == "float[]" or t.startswith("java.nio.FloatBuffer"): return "GLfloat"
    if t == "long[]" or t.startswith("java.nio.LongBuffer"): return "GLint64"
    # byte arrays: element-addressable as GLbyte so a trailing offset can be
    # applied with well-defined 1-byte pointer arithmetic (void* math is
    # nonstandard / a clang error). The GL fn-pointer arg is still void* below.
    if t == "byte[]": return "GLbyte"
    if t in ("java.nio.ByteBuffer","java.nio.Buffer"): return "void"
    if t == "boolean[]": return "GLboolean"
    return "void"

def emit_cpp(cls, methods):
    """Return (bridge_defs_str, table_entries_list)."""
    defs = []
    table = []
    name_counts = {}
    for _, name, _ in methods:
        name_counts[name] = name_counts.get(name, 0) + 1
    seen = {}
    for ret, name, params in methods:
        seen[name] = seen.get(name, 0) + 1
        idx = seen[name]
        total = name_counts[name]
        fn = cpp_name(cls, name, idx, total)
        # Build typed fn-pointer signature for the GL entry point.
        gl_ret = CPP_TYPEDEF.get(ret, "void") if ret in CPP_TYPEDEF else \
                 ("const char*" if "String" in ret else
                  ("GLint64" if ret == "long" else
                   ("GLboolean" if ret == "boolean" else "void*")))
        # JNI bridge signature.
        sig = ["JNIEnv* env", "jclass"]
        for i, p in enumerate(params):
            sig.append(cpp_param_decl(p, i))
        ret_jni = {"void":"void","int":"jint","boolean":"jboolean",
                   "float":"jfloat","long":"jlong"}.get(ret)
        if ret_jni is None:
            ret_jni = "jstring" if ret == "java.lang.String" else \
                      ("jobjectArray" if ret == "java.lang.String[]" else
                       ("jobject" if ret.startswith("java.nio.") or
                        ret in CB else "void"))
        body = gen_body(name, ret, params, gl_ret)
        defs.append("%s%s %s(%s) {\n%s}\n" %
                    (gen_lead(name, params), ret_jni, fn,
                     ", ".join(sig), body))
        table.append((name, descriptor(ret, params), fn))
    return "\n".join(defs), table

def gen_lead(name, params):
    """Comment block emitted immediately above a bridge, or ""."""
    if any(p in CB for p in params):
        srcfile = ("android_opengl_GLES31Ext.cpp:558-560"
                   if "KHR" in name else "android_opengl_GLES32.cpp:588-592")
        return (
            "// AOSP does NOT wire a DebugProc through to the driver -- its JNI\n"
            "// entry point throws outright (frameworks/base core/jni/%s,\n"
            "// android_%s -> jniThrowException(_env,\n"
            '//   "java/lang/UnsupportedOperationException", "not yet implemented")).\n'
            "// Handing the driver a NULL callback instead is a SILENT no-op: the app\n"
            "// believes its GL_KHR_debug hook is live and then hears nothing. Throwing\n"
            "// makes an engine's GL-validation path take the same branch it takes on a\n"
            "// device.\n" % (srcfile, name))
    return ""


# Emitted once at the top of gles3_bridges.inc. egl14_bridges.inc (included
# later in the same namespace by native_methods.cpp) uses the same function.
JNI_CRITICAL_GATE_PREAMBLE = """\
// No JNI call inside a GetPrimitiveArrayCritical region (JNI spec; jdk21u
// jniCheck.cpp functionEnter warns "Calling other JNI functions in the scope
// of Get/ReleasePrimitiveArrayCritical or Get/ReleaseStringCritical"). On JDK
// 25 a GC request waits for every thread to leave its critical region, the
// requester included (JDK-8192647), so an allocating JNI call inside one can
// hang the process. docs/gclocker-critical-release-design_2026-09-25.md.
// BISECT GATE, default ON: MACAPK_JNI_NO_CALLS_IN_CRITICAL=0 restores the
// pre-fix call order in the bridges that had a JNI call inside a critical
// (here and in egl14_bridges.inc).
bool jni_no_calls_in_critical() {
    static const bool on = [] {
        const char* e = std::getenv("MACAPK_JNI_NO_CALLS_IN_CRITICAL");
        return !(e && std::strcmp(e, "0") == 0);
    }();
    return on;
}

"""

_GATED_ASSIGN_RE = re.compile(r"^(\s*)((?:const )?\w+\* )(\w+) = (.*);\n$")

def order_critical_windows(name, marshal, cleanup):
    """Return (marshal_lines, cleanup_lines) with no JNI call inside a critical.

    WHY. A GetPrimitiveArrayCritical region forbids every other JNI call
    (JNI spec, "GetPrimitiveArrayCritical ... the native code should not ...
    call other JNI functions"). jdk21u's -Xcheck:jni flags the violation in
    jniCheck.cpp functionEnter() ("Calling other JNI functions in the scope of
    Get/ReleasePrimitiveArrayCritical or Get/ReleaseStringCritical"). On our
    JDK 21 SerialGC an allocation there expands the heap WHILE IT CAN; once the
    heap is at -Xmx, jdk21u genCollectedHeap.cpp mem_allocate_work (:312-348)
    returns nullptr to the thread inside the critical (an OutOfMemoryError, or
    fatal "Possible deadlock due to allocating while in jni critical section"
    under -Xcheck:jni) and stalls every other allocating thread in
    GCLocker::stall_until_clear. On JDK 25 (JDK-8192647) a GC request waits for
    EVERY thread to leave its critical region, the requester included, so an
    allocating call inside one can hang the process at any heap size
    (docs/gclocker-critical-release-design_2026-09-25.md, 2.2 and the
    ADVERSARIAL CRITIQUE P0 #1). AOSP's generated bindings have the same
    shape as the fixed output: android_opengl_GLES30.cpp (android14-release)
    glGetProgramBinary resolves its Buffer with getPointer() BEFORE its one
    GetPrimitiveArrayCritical, and copies the int[] out-params with
    GetIntArrayElements.

    The rule: every non-pin marshal line runs before the first pin, and every
    pin release runs before the other cleanup. A function whose param order
    already satisfies it is emitted byte-for-byte as before. A function that
    does NOT (today: glGetProgramBinary_1, glGetUniformIndices_1) gets BOTH
    orders behind the MACAPK_JNI_NO_CALLS_IN_CRITICAL bisect gate (default ON;
    =0 restores the pre-fix order), via jni_no_calls_in_critical() in this
    file's preamble."""
    old_m = [t for _, t in marshal]
    new_m = [t for k, t in marshal if k != "pin"] + [t for k, t in marshal if k == "pin"]
    old_c = [t for _, t in cleanup]
    new_c = [t for k, t in cleanup if k == "pin"] + [t for k, t in cleanup if k != "pin"]
    if new_m == old_m and new_c == old_c:
        return old_m, old_c
    # One gate read per call, declared before the first marshal line so both
    # the marshal and the cleanup halves can use it.
    out_m = ["    const bool _nc = jni_no_calls_in_critical();  // MACAPK_JNI_NO_CALLS_IN_CRITICAL\n"]
    out_c = []
    if new_m != old_m:
        seen_pin = False
        moved = set()
        for k, t in marshal:
            if k == "pin": seen_pin = True
            elif seen_pin:
                if k != "jni":
                    # A multi-line marshal (the String[] walk) has no single
                    # assignment to split; refuse rather than emit it wrong.
                    raise SystemExit("order_critical_windows: cannot gate a %s "
                                     "line after a pin in %s" % (k, name))
                moved.add(t)
        # Gate ON: every non-pin line first, moved ones as a guarded assign.
        for k, t in marshal:
            if k == "pin": continue
            if t in moved:
                m = _GATED_ASSIGN_RE.match(t)
                if not m:
                    raise SystemExit("order_critical_windows: unexpected line "
                                     "shape in %s: %r" % (name, t))
                ind, ty, var, expr = m.groups()
                out_m.append("%s%s%s = nullptr;\n" % (ind, ty, var))
                out_m.append("%sif (_nc) %s = %s;\n" % (ind, var, expr))
            else:
                out_m.append(t)
        # Then the pins in their old order, with each moved line re-run at its
        # OLD position when the gate is off (the pre-fix order, exactly).
        for k, t in marshal:
            if k == "pin":
                out_m.append(t)
            elif t in moved:
                ind, _, var, expr = _GATED_ASSIGN_RE.match(t).groups()
                out_m.append("%sif (!_nc) %s = %s;\n" % (ind, var, expr))
    else:
        out_m += old_m
    if new_c != old_c:
        pin_on = lambda t: t.replace("    if (a", "    if (_nc && a", 1)
        pin_off = lambda t: t.replace("    if (a", "    if (!_nc && a", 1)
        for k, t in cleanup:
            if k == "pin":
                if not t.startswith("    if (a"):
                    raise SystemExit("order_critical_windows: unexpected release "
                                     "shape in %s: %r" % (name, t))
                out_c.append(pin_on(t))
        for k, t in cleanup:
            out_c.append(pin_off(t) if k == "pin" else t)
    else:
        out_c = old_c
    return out_m, out_c


def gen_body(name, ret, params, gl_ret):
    """Emit the marshaling body. Resolve the GL symbol, marshal args, call."""
    L = []
    if any(p in CB for p in params):
        # See gen_lead(): AOSP throws rather than registering the hook.
        for i, _ in enumerate(params):
            L.append("    (void)a%d;\n" % i)
        L.append('    jclass ex = env->FindClass('
                 '"java/lang/UnsupportedOperationException");\n')
        L.append('    if (ex) env->ThrowNew(ex, "not yet implemented");\n')
        if ret != "void":
            L.append("    return %s;\n" %
                     ("nullptr" if ret not in ("int", "long", "boolean", "float")
                      else "0"))
        return "".join(L)
    L.append('    static auto _p = (void*)gl3_resolve("%s");\n' % name)
    # Offset preflight. Every `<type>[] aN, int aN+1` pair becomes raw pointer
    # arithmetic below; unchecked, an app-supplied offset is a heap OOB read and
    # write. gl3_check_offset() enforces AOSP's floor (offset >= 0 and at least
    # one element remaining) and throws IllegalArgumentException otherwise, the
    # same exception AOSP's generated bindings raise. This MUST precede every
    # GetPrimitiveArrayCritical -- JNI forbids FindClass/ThrowNew inside a
    # critical section.
    ret_zero = ("" if ret == "void" else
                (" 0" if ret in ("int", "long", "boolean", "float")
                 else " nullptr"))
    for i, p in enumerate(params):
        if pclass(p) == "primarray" and i + 1 < len(params) \
                and is_offset_param(params, i + 1):
            L.append('    if (!gl3_check_offset(env, a%d, a%d, '
                     '"%s: offset out of range")) return%s;\n'
                     % (i, i + 1, name, ret_zero))
    # Determine GL fn-pointer typedef arglist + the call argument expressions.
    #
    # Every marshal line and every cleanup line is tagged "pin" (a
    # GetPrimitiveArrayCritical / its Release) or "jni" (any other JNI work:
    # GetStringUTFChars, the String[] walk, gl3_buffer_ptr's CallIntMethod).
    # order_critical_windows() then puts every "jni" marshal line BEFORE the
    # first pin and every pin release BEFORE the other cleanup, so no JNI call
    # ever runs inside a critical region. See its header for why.
    gl_args_types = []
    call_args = []
    cleanup = []
    skip = set()
    L_pre = L
    L = []
    for i, p in enumerate(params):
        if i in skip: continue
        cls_ = pclass(p)
        if cls_ == "scalar":
            cty = CPP_TYPEDEF[p]
            gl_args_types.append(cty)
            call_args.append("(%s)a%d" % (cty, i))
        elif cls_ == "bool":
            gl_args_types.append("GLboolean")
            call_args.append("(GLboolean)a%d" % i)
        elif cls_ == "callback":
            # Real GL callback registration is unsupported; pass null fn.
            gl_args_types.append("const void*")
            call_args.append("nullptr")
            # also drop a following userParam if present? AOSP DebugProc binds
            # only the callback object, so nothing else to skip.
        elif cls_ == "string":
            ct = gl_ctype(p)
            L.append(("jni", '    const char* s%d = a%d ? env->GetStringUTFChars(a%d, nullptr) : nullptr;\n' % (i, i, i)))
            gl_args_types.append("const GLchar*")
            call_args.append("(const GLchar*)s%d" % i)
            cleanup.append(("jni", '    if (a%d) env->ReleaseStringUTFChars(a%d, s%d);\n' % (i, i, i)))
        elif cls_ == "strarray":
            L.append(("jni-multi", "    std::vector<const char*> sv%d; std::vector<jstring> sj%d;\n" % (i, i)))
            L.append(("jni-multi", "    jsize sn%d = a%d ? env->GetArrayLength(a%d) : 0;\n" % (i, i, i)))
            L.append(("jni-multi", "    for (jsize k=0;k<sn%d;++k){ jstring js=(jstring)env->GetObjectArrayElement(a%d,k); sj%d.push_back(js); sv%d.push_back(js?env->GetStringUTFChars(js,nullptr):nullptr);}\n" % (i, i, i, i)))
            gl_args_types.append("const GLchar* const*")
            call_args.append("(const GLchar* const*)(sv%d.empty()?nullptr:sv%d.data())" % (i, i))
            cleanup.append(("jni", "    for (jsize k=0;k<sn%d;++k){ if(sj%d[k]) env->ReleaseStringUTFChars(sj%d[k], sv%d[k]); }\n" % (i, i, i, i)))
        elif cls_ == "primarray":
            cty = gl_ctype(p)
            # check for trailing offset param
            off = None
            if i + 1 < len(params) and is_offset_param(params, i + 1):
                off = i + 1
                skip.add(off)
            L.append(("pin", "    void* base%d = a%d ? env->GetPrimitiveArrayCritical(a%d, nullptr) : nullptr;\n" % (i, i, i)))
            ptr = "(%s*)base%d" % (cty, i)
            if off is not None:
                ptr = "(base%d ? (%s*)base%d + a%d : nullptr)" % (i, cty, i, off)
            gl_args_types.append("%s*" % cty)
            call_args.append(ptr)
            cleanup.append(("pin", "    if (a%d) env->ReleasePrimitiveArrayCritical(a%d, base%d, 0);\n" % (i, i, i)))
        elif cls_ == "buffer":
            cty = gl_ctype(p)
            L.append(("jni", "    void* buf%d = a%d ? gl3_buffer_ptr(env, a%d) : nullptr;\n" % (i, i, i)))
            gl_args_types.append("%s*" % cty if cty != "void" else "void*")
            call_args.append("(%s*)buf%d" % (cty, i) if cty != "void" else "buf%d" % i)
    L, cleanup = order_critical_windows(name, L, cleanup)
    L = L_pre + L
    # Build the typed call.
    cargs = ", ".join(gl_args_types) if gl_args_types else "void"
    fnptr_t = "%s(*)(%s)" % (gl_ret, cargs)
    call = "((%s)_p)(%s)" % (fnptr_t, ", ".join(call_args))
    if ret == "void":
        L.append("    if (_p) %s;\n" % call)
        L += cleanup
    elif ret in ("int","long","boolean","float"):
        rj = {"int":"jint","long":"jlong","boolean":"jboolean","float":"jfloat"}[ret]
        zero = "0"
        L.append("    %s _r = _p ? (%s)%s : (%s)%s;\n" % (rj, rj, call, rj, zero))
        L += cleanup
        L.append("    return _r;\n")
    else:
        # String / String[] / Buffer returns: best-effort via helper.
        #
        # Only glGetStringi maps 1:1 to a real GLES3 C entry point that
        # returns a (const GLubyte*) string. The other String-returning
        # methods (glGetActiveUniformBlockName, glGetProgramResourceName,
        # glGetProgramPipelineInfoLog, glGetTransformFeedbackVarying,
        # glGetObjectLabel*, glGetObjectPtrLabel*) are AOSP *convenience*
        # overloads with NO matching C symbol of that arity -- calling the
        # resolved void(...) function as if it returned a char* would invoke
        # real GL with garbage args. So for those we return "" WITHOUT calling.
        STRING_REAL = {"glGetStringi"}
        if ret == "java.lang.String" and name in STRING_REAL:
            L.append("    const char* _r = _p ? (const char*)%s : nullptr;\n" % call)
            L += cleanup
            L.append("    return _r ? env->NewStringUTF(_r) : env->NewStringUTF(\"\");\n")
        elif ret == "java.lang.String":
            L += cleanup
            L.append("    (void)_p; return env->NewStringUTF(\"\");\n")
        else:
            # Buffer / String[] returns are rare (glMapBufferRange etc.); we
            # return null so the call is observable-but-safe rather than wrong.
            L += cleanup
            L.append("    (void)_p; return nullptr;\n")
    return "".join(L)

# ---------------- EGL14 / EGL15 / EGLExt Java emitter ----------------
#
# The EGL binding is object-oriented (returns/takes EGLDisplay/Context/Surface/
# Config/Image/Sync handle wrappers), so its native bridges are hand-written in
# native_methods.cpp (handle marshaling is not mechanical). Here we only emit
# the Java class: exact AOSP constants + native decls + the handful of
# non-native helper methods (the EGL_NO_* object fields, eglCreateWindowSurface
# overloads). The C++ table EGL14 registration is hand-maintained but checked
# against this generated decl list, keeping decl<->registration in lockstep.
EGL_NATIVE_RE = re.compile(
    r"public static native\s+([\w.$\[\]]+)\s+(\w+)\s*\(([^)]*)\)")

EGL_HANDLE = {
    "android.opengl.EGLDisplay","android.opengl.EGLContext",
    "android.opengl.EGLSurface","android.opengl.EGLConfig",
    "android.opengl.EGLImage","android.opengl.EGLSync",
}

def egl_jtype(t):
    if t.startswith("android.opengl.EGL"):
        return t.split(".")[-1]
    return java_type(t)

def emit_egl_java(cls):
    objfields = []  # (type, name)
    consts = []     # (kind,name,val)
    natives = []    # (ret,name,params)
    extra = []      # raw non-native helper method lines (eglCreateWindowSurface)
    with open(os.path.join(SIG_DIR, cls + ".txt")) as f:
        for line in f:
            mc = CONST_RE.search(line)
            if mc:
                consts.append((mc.group(1), mc.group(2), mc.group(3))); continue
            mo = re.search(r"public static (android\.opengl\.EGL\w+) (\w+);", line)
            if mo:
                objfields.append((mo.group(1).split(".")[-1], mo.group(2))); continue
            mn = EGL_NATIVE_RE.search(line)
            if mn:
                ret, name, args = mn.group(1), mn.group(2), mn.group(3).strip()
                params = [a.strip() for a in args.split(",")] if args else []
                natives.append((ret, name, params)); continue
    out = []
    out.append("// android.opengl.%s -- EGL 1.4/1.5 Java binding.\n" % cls)
    out.append("//\n// GENERATED Java decls (constants + native signatures) by\n"
               "// debug/gles_gen/gen.py from android-34. The native bridges live in\n"
               "// runtime/src/native_methods.cpp (hand-written: handle marshaling),\n"
               "// registered in the kEgl14Methods/kEgl15Methods/kEglExtMethods tables.\n"
               "// Mirrors AOSP android.opengl.%s. No em dashes.\n" % cls)
    out.append("package android.opengl;\n\n")
    out.append("import java.nio.Buffer;\n\n")
    out.append("public class %s {\n    public %s() {}\n\n" % (cls, cls))
    for kind, name, val in consts:
        if kind == "long":
            out.append("    public static final long %s = %sL;\n" % (name, val))
        else:
            out.append("    public static final int %s = %s;\n" % (name, val))
    if consts: out.append("\n")
    # Object handle fields: EGL_NO_DISPLAY etc. = handle 0 wrappers.
    for typ, name in objfields:
        out.append("    public static final %s %s = new %s(0L);\n"
                   % (typ, name, typ))
    if objfields: out.append("\n")
    for ret, name, params in natives:
        dp = ", ".join("%s a%d" % (egl_jtype(p), i)
                       for i, p in enumerate(params))
        out.append("    public static native %s %s(%s);\n"
                   % (egl_jtype(ret), name, dp))
    # EGL14.eglCreateWindowSurface(EGLDisplay, EGLConfig, Object win, int[], int)
    # is NOT native on AOSP -- it unwraps the Surface to a native window then
    # calls a private native _eglCreateWindowSurface. We provide it as a thin
    # native method too (the C++ side handles the Object), so emit it as native
    # only when present in the javap (it shows as non-native there). Emit a
    # native passthrough taking Object.
    if cls == "EGL14":
        out.append("    public static native EGLSurface eglCreateWindowSurface("
                   "EGLDisplay a0, EGLConfig a1, Object a2, int[] a3, int a4);\n")
    out.append("}\n")
    with open(os.path.join(JAVA_DIR, cls + ".java"), "w") as f:
        f.write("".join(out))
    return len(natives) + (1 if cls == "EGL14" else 0)

