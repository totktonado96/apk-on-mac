#!/usr/bin/env python3
# gen_system_fonts.py -- generate runtime/translator/src/pairip_system_fonts.h from a captured
# device ASystemFontIterator dump (debug/pairip_devhook/refs/dev_fontlist_api34_*.txt).
#
# WHY: pairip 52.3's anti-tamper VM enumerates the system fonts via the NDK AFont API and folds
# path+weight+italic+axes per font (docs/pairip-523-crack-state cont.301/302). Apk on Mac has no native
# AFont impl, so its fold is empty and the VM diverges at pass 16645. This emits the AOSP-API-34 font
# TABLE (a platform-stable surface, like AOSP source) that bionic_shim.cpp's __macapk_arm64_AFont_*
# return, so our ASystemFontIterator output matches a real device's. Regenerate if the oracle image
# changes:  python3 debug/gen_system_fonts.py <dump.txt>  ->  runtime/translator/src/pairip_system_fonts.h
import re, sys, os
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "debug/pairip_devhook/refs/dev_fontlist_api34_523_2026-10-14.txt")
OUT = os.path.join(REPO, "runtime/translator/src/pairip_system_fonts.h")
LINE = re.compile(r'^\[(\d+)\] path=(\S+) weight=(\d+) italic=(\d+) ci=(\d+) locales=(\S+) axes=(.*)$')

def tag4cc(s):
    s = (s + '\0\0\0\0')[:4]
    return (ord(s[0]) << 24) | (ord(s[1]) << 16) | (ord(s[2]) << 8) | ord(s[3])

fonts = []
for ln in open(SRC):
    m = LINE.match(ln.rstrip('\n'))
    if not m:
        continue
    idx, path, weight, italic, ci, loc, axes_s = m.groups()
    axes = []
    for tok in axes_s.split():
        if '=' not in tok:
            continue
        tag, val = tok.split('=', 1)
        axes.append((tag4cc(tag), float(val)))
    loc = None if loc == '(null)' else loc
    fonts.append(dict(path=path, weight=int(weight), italic=int(italic), ci=int(ci), loc=loc, axes=axes))

with open(OUT, 'w') as f:
    f.write("// pairip_system_fonts.h -- AUTO-GENERATED by debug/gen_system_fonts.py. DO NOT EDIT.\n")
    f.write("// The AOSP-API-34 system font table that bionic_shim.cpp's NDK AFont/ASystemFontIterator\n")
    f.write("// shims return, so pairip's font fold (pass 16645) matches a real device. Source:\n")
    f.write("// %s\n" % os.path.relpath(SRC, REPO))
    f.write("#pragma once\n#include <cstdint>\n#include <cstddef>\n\n")
    f.write("struct MacApkFontAxis { uint32_t tag; float value; };\n")
    f.write("struct MacApkSysFont { const char* path; uint16_t weight; uint8_t italic;\n")
    f.write("                       uint32_t collectionIndex; uint32_t naxes;\n")
    f.write("                       const MacApkFontAxis* axes; const char* locales; };\n\n")
    for i, ft in enumerate(fonts):
        if ft['axes']:
            f.write("static const MacApkFontAxis g_macapk_font_axes_%d[] = { " % i)
            f.write(", ".join("{0x%08xu, %.6ff}" % (t, v) for (t, v) in ft['axes']))
            f.write(" };\n")
    f.write("\nstatic const MacApkSysFont g_macapk_sys_fonts[] = {\n")
    for i, ft in enumerate(fonts):
        axptr = ("g_macapk_font_axes_%d" % i) if ft['axes'] else "nullptr"
        loc = ('"%s"' % ft['loc']) if ft['loc'] else "nullptr"
        f.write('  {"%s", %d, %d, %d, %d, %s, %s},\n' %
                (ft['path'], ft['weight'], ft['italic'], ft['ci'], len(ft['axes']), axptr, loc))
    f.write("};\n")
    f.write("static const int g_macapk_sys_fonts_n = %d;\n" % len(fonts))

print("wrote %s: %d fonts (%d with axes, %d with locales)" %
      (OUT, len(fonts), sum(1 for x in fonts if x['axes']), sum(1 for x in fonts if x['loc'])))
