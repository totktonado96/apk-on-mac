#!/usr/bin/env bash
# refresh_angle_prebuilt.sh -- copy the COMPILED ANGLE + Vulkan-backend binaries and
# the GLES/EGL headers out of the local ANGLE build into the TRACKED directory
# thirdparty/angle-prebuilt/, with a PROVENANCE.txt naming exactly what they were
# built from.
#
# WHY (owner, 2026-09-26): "Make sure we don't upload the entire angle to the GitHub,
# but we do upload the compiled binaries." The ANGLE source is a ~25 GB Chromium
# checkout (thirdparty/angle/, gitignored, rebuilt by scripts/build_angle.sh in
# 30-60 min). Before this script the compiled dylibs were not in git at all, so a
# fresh clone could not build a runtime that renders without that whole checkout.
# The binaries are ~20 MB; runtime/CMakeLists.txt, runtime/translator/CMakeLists.txt
# and runtime/scripts/build.sh fall back to this directory when thirdparty/angle/out
# is absent.
#
# Called automatically at the end of scripts/build_angle.sh and
# scripts/build_moltenvk.sh. Idempotent: a file whose bytes did not change is not
# rewritten, so a no-op rebuild leaves git clean.
#
# USAGE
#   scripts/refresh_angle_prebuilt.sh            # refresh from thirdparty/angle/out/Release
#   scripts/refresh_angle_prebuilt.sh --check    # exit 1 (and say which) if the tracked
#                                                # binaries differ from the local build
set -euo pipefail
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ANGLE_DIR="$PROJECT_DIR/thirdparty/angle"
SRC="$ANGLE_DIR/out/Release"
DST="$PROJECT_DIR/thirdparty/angle-prebuilt"
LIBS="libGLESv2.dylib libEGL.dylib libvulkan.dylib libMoltenVK.dylib MoltenVK_icd.json"
# Only the header families the runtime and the bionic shim compile against
# (runtime/src/angle_glue.*, gles/egl bridges, translator bionic_shim.cpp).
HDRS="EGL GLES GLES2 GLES3 KHR platform angle_gl.h export.h"

MODE=refresh; [ "${1:-}" = "--check" ] && MODE=check
if [ ! -f "$SRC/libGLESv2.dylib" ]; then
    echo "refresh_angle_prebuilt: no local ANGLE build at $SRC -- nothing to do" >&2
    exit 0
fi

same() { [ -f "$2" ] && cmp -s "$1" "$2"; }

stale=0
for f in $LIBS; do
    [ -f "$SRC/$f" ] || continue
    if ! same "$SRC/$f" "$DST/lib/$f"; then
        stale=1
        [ "$MODE" = check ] && echo "STALE thirdparty/angle-prebuilt/lib/$f differs from $SRC/$f"
    fi
done
if [ "$MODE" = check ]; then
    [ $stale = 0 ] && echo "angle-prebuilt: matches the local ANGLE build"
    exit $stale
fi

mkdir -p "$DST/lib" "$DST/include"
for f in $LIBS; do
    [ -f "$SRC/$f" ] || continue
    same "$SRC/$f" "$DST/lib/$f" || { cp -p "$SRC/$f" "$DST/lib/$f"; echo "angle-prebuilt: updated lib/$f"; }
done
for h in $HDRS; do
    [ -e "$ANGLE_DIR/include/$h" ] || continue
    rsync -a --delete "$ANGLE_DIR/include/$h" "$DST/include/"
done

{
    echo "# thirdparty/angle-prebuilt -- COMPILED ANGLE for Apk on Mac (generated by"
    echo "# scripts/refresh_angle_prebuilt.sh; do not hand-edit). Rebuild from source with"
    echo "# scripts/build_angle.sh, which re-runs this script at the end."
    echo "angle_commit      $(git -C "$ANGLE_DIR" rev-parse HEAD 2>/dev/null || echo unknown)"
    if [ -d "$PROJECT_DIR/thirdparty/MoltenVK-build/.git" ]; then
        echo "moltenvk_commit   $(git -C "$PROJECT_DIR/thirdparty/MoltenVK-build" rev-parse HEAD)"
    fi
    for p in "$PROJECT_DIR"/thirdparty/angle-patches/*.patch "$PROJECT_DIR"/thirdparty/moltenvk-patches/*.patch; do
        [ -f "$p" ] && echo "patch             $(md5 -q "$p")  ${p#$PROJECT_DIR/}"
    done
    for f in $LIBS; do
        [ -f "$DST/lib/$f" ] && echo "binary            $(md5 -q "$DST/lib/$f")  lib/$f"
    done
    echo "host              $(sw_vers -productVersion) $(uname -m)"
} > "$DST/PROVENANCE.txt.tmp"
# Keep the file byte-stable when nothing but the timestamp would change.
if ! cmp -s "$DST/PROVENANCE.txt.tmp" "$DST/PROVENANCE.txt"; then
    mv "$DST/PROVENANCE.txt.tmp" "$DST/PROVENANCE.txt"
    echo "angle-prebuilt: PROVENANCE.txt updated"
else
    rm -f "$DST/PROVENANCE.txt.tmp"
fi
